// Helper to generate a pre-filled WhatsApp order link for any product
export function getProductWhatsAppUrl(product: Product, size?: string): string {
  const phone = '923055177531';
  const sizeText = size ? ` (Size: ${size})` : '';
  const message = `Assalam-o-Alaikum M Muzamil! 🛍️\n\nI want to order:\n*Product:* ${product.name}${sizeText}\n*Price:* Rs. ${product.price.toLocaleString()}\n*Code:* ${product.id}\n\nPlease confirm availability and delivery to my address.`;
  return `https://wa.me/${phone}?text=${encodeURIComponent(message)}`;
}

// Helper to generate a pre-filled WhatsApp link for general gift order inquiries
export function getGiftOrderWhatsAppUrl(giftCode: string, recipient: string, item: string): string {
  const phone = '923055177531';
  const message = `Assalam-o-Alaikum M Muzamil! 🎁\n\nI have created a Private Gift Order!\n*Gift Code:* ${giftCode}\n*Recipient:* ${recipient}\n*Item:* ${item}\n\nPlease process this gift package with the secret QR code card.`;
  return `https://wa.me/${phone}?text=${encodeURIComponent(message)}`;
}
